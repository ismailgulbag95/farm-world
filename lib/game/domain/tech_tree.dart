class TechTreeEngine {
  const TechTreeEngine();

  bool _isOwned(String id, OpeningSession session) =>
      session.hasPurchasedTechnology(id) ||
      (id == 'H01' && session.hasMower) ||
      (id == 'H02' && session.hasWorker);

  TechNodeStatus getNodeStatus(
    TechNode node,
    OpeningSession session, {
    bool researchOnly = false,
  }) {
    if (_isOwned(node.id, session)) return TechNodeStatus.purchased;
    for (final id in node.prereqIds) {
      if (!_isOwned(id, session)) return TechNodeStatus.locked;
    }
    if (node.alternativePrerequisiteSets.isNotEmpty &&
        !node.alternativePrerequisiteSets.any(
          (route) => route.every((id) => _isOwned(id, session)),
        )) {
      return TechNodeStatus.locked;
    }
    if (!researchOnly) {
      if (session.lifetimeProductionEvidence < node.requiredEvidenceP ||
          session.cropDiversityCount < node.requiredDiversityV) {
        return TechNodeStatus.locked;
      }
      if (node.requiredDeliveriesD > 0) {
        final deliveries = session.fleetManager.vehicles.fold<int>(
          0,
          (sum, v) => sum + v.totalDeliveriesCount,
        );
        if (deliveries < node.requiredDeliveriesD) return TechNodeStatus.locked;
      }
    }
    return TechNodeStatus.unlockable;
  }

  bool canPurchaseNode(
    String id,
    OpeningSession session, {
    bool researchOnly = false,
  }) {
    final node = TechTreeCatalog.byId(id);
    return node != null &&
        node.implementationStatus !=
            TechNodeImplementationStatus.unsupported &&
        getNodeStatus(node, session, researchOnly: researchOnly) ==
            TechNodeStatus.unlockable &&
        session.farmCredits >= node.creditCost;
  }

  bool purchaseNode(
    String id,
    OpeningSession session, {
    bool researchOnly = false,
  }) {
    final node = TechTreeCatalog.byId(id);
    if (node == null ||
        !canPurchaseNode(id, session, researchOnly: researchOnly)) {
      return false;
    }
    session.addCredits(-node.creditCost);
    session.unlockTechnology(node.id);
    return true;
  }
}
