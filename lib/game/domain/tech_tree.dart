import 'opening_session.dart';

enum TechMainBranch {
  production('ÜRETİM', '🌾'),
  logistics('LOJİSTİK', '🚛'),
  landDevelopment('ARAZİ GELİŞTİRME', '🗺️');

  const TechMainBranch(this.title, this.icon);
  final String title;
  final String icon;
}

/// Existing specialty IDs remain stable and are grouped into three visible trunks.
enum TechBranch {
  labor('H: Emek & Araçlar', '🚜'),
  agriculture('T: Tarla & Toprak', '🌱'),
  crops('CR: Ekin Aileleri', '🌾'),
  processing('PR: İşleme & Fabrika', '🏭'),
  logistics('L: Lojistik & Filo', '🚛'),
  storage('S: Ambar & Pazar', '📦'),
  livestock('LV: Hayvancılık', '🐔'),
  expansion('I: Arazi & İklim', '🗺️'),
  automation('O: Otomasyon', '⚙️');

  const TechBranch(this.title, this.icon);
  final String title;
  final String icon;

  TechMainBranch get mainBranch => switch (this) {
    TechBranch.labor ||
    TechBranch.agriculture ||
    TechBranch.crops ||
    TechBranch.processing ||
    TechBranch.livestock => TechMainBranch.production,
    TechBranch.logistics ||
    TechBranch.storage ||
    TechBranch.automation => TechMainBranch.logistics,
    TechBranch.expansion => TechMainBranch.landDevelopment,
  };
}

enum TechNodeStatus { locked, unlockable, purchased }

/// What a purchased node currently does in the playable game.
///
/// This is deliberately separate from [TechNodeStatus], which only reports
/// whether the player has met the purchase requirements.
enum TechNodeImplementationStatus {
  runtimeEffect,
  permissionGate,
  prerequisiteOnly,
  unsupported,
}

class TechNode {
  const TechNode({
    required this.id,
    required this.name,
    required this.branch,
    this.track = '',
    required this.description,
    required this.unlocksDescription,
    required this.creditCost,
    this.prereqIds = const [],
    this.alternativePrerequisiteSets = const [],
    this.requiredEvidenceP = 0,
    this.requiredDeliveriesD = 0,
    this.requiredDiversityV = 0,
  });

  final String id;
  final String name;
  final TechBranch branch;
  final String track;
  TechMainBranch get mainBranch => branch.mainBranch;
  final String description;
  final String unlocksDescription;
  final int creditCost;

  /// Every technology in this list must be purchased (AND).
  final List<String> prereqIds;

  /// At least one complete route must be purchased; IDs within a route are AND.
  final List<List<String>> alternativePrerequisiteSets;
  final int requiredEvidenceP;
  final int requiredDeliveriesD;
  final int requiredDiversityV;

  TechNodeImplementationStatus get implementationStatus =>
      TechTreeCatalog.implementationStatusFor(this);

  /// The truthful, currently implemented effect or limitation of this node.
  String get currentEffectDescription =>
      TechTreeCatalog.currentEffectDescriptionFor(this);
}

class _TechNodeSpec {
  const _TechNodeSpec(
    this.id,
    this.name,
    this.branch,
    this.track, {
    this.prereqIds = const [],
    required this.creditCost,
    required this.description,
    required this.unlocksDescription,
    this.alternativePrerequisiteSets = const [],
    this.requiredEvidenceP = 0,
    this.requiredDeliveriesD = 0,
    this.requiredDiversityV = 0,
  });
  final String id, name, track, description, unlocksDescription;
  final TechBranch branch;
  final List<String> prereqIds;
  final List<List<String>> alternativePrerequisiteSets;
  final int creditCost,
      requiredEvidenceP,
      requiredDeliveriesD,
      requiredDiversityV;
  TechNode toNode() => TechNode(
    id: id,
    name: name,
    branch: branch,
    track: track,
    description: description,
    unlocksDescription: unlocksDescription,
    creditCost: creditCost,
    prereqIds: prereqIds,
    alternativePrerequisiteSets: alternativePrerequisiteSets,
    requiredEvidenceP: requiredEvidenceP,
    requiredDeliveriesD: requiredDeliveriesD,
    requiredDiversityV: requiredDiversityV,
  );
}

