  static final Map<String, Set<String>> _dependentTechnologyIds =
      _buildDependentTechnologyIds();
  static final Set<String> _treeAdvancingTechnologyIds =
      _buildTreeAdvancingTechnologyIds();

  static TechNodeImplementationStatus implementationStatusFor(TechNode node) {
    if (_runtimeEffects.containsKey(node.id)) {
      return TechNodeImplementationStatus.runtimeEffect;
    }
    if (_permissionGateEffects.containsKey(node.id)) {
      return TechNodeImplementationStatus.permissionGate;
    }
    if (_treeAdvancingTechnologyIds.contains(node.id)) {
      return TechNodeImplementationStatus.prerequisiteOnly;
    }
    return TechNodeImplementationStatus.unsupported;
  }

  static String currentEffectDescriptionFor(TechNode node) {
    final runtimeEffect = _runtimeEffects[node.id];
    if (runtimeEffect != null) return runtimeEffect;
    final permissionEffect = _permissionGateEffects[node.id];
    if (permissionEffect != null) return permissionEffect;
    return switch (implementationStatusFor(node)) {
      TechNodeImplementationStatus.runtimeEffect =>
        'Bu teknolojinin oyundaki etkisi araştırma kataloğunda tanımlı.',
      TechNodeImplementationStatus.permissionGate =>
        'Bu teknoloji mevcut bir mağaza, inşaat veya işlem iznini açar.',
      TechNodeImplementationStatus.prerequisiteOnly =>
        'Tek başına oyun etkisi yoktur; teknoloji ağacındaki sonraki düğümlerin ön koşuludur.',
      TechNodeImplementationStatus.unsupported =>
        'Bu düğümün ve bağlı olduğu araştırma zincirinin oyunda çalışan bir etkisi yoktur. Araştırma satın alımı kapalıdır.',
    };
  }

  static Map<String, Set<String>> _buildDependentTechnologyIds() {
    final dependents = <String, Set<String>>{
      for (final node in all) node.id: <String>{},
    };
    for (final node in all) {
      final prerequisites = <String>{
        ...node.prereqIds,
        for (final route in node.alternativePrerequisiteSets) ...route,
      };
      for (final prerequisiteId in prerequisites) {
        dependents[prerequisiteId]?.add(node.id);
      }
    }
    return Map.unmodifiable({
      for (final entry in dependents.entries)
        entry.key: Set<String>.unmodifiable(entry.value),
    });
  }

  static Set<String> _buildTreeAdvancingTechnologyIds() {
    final advancing = <String>{
      ..._runtimeEffects.keys,
      ..._permissionGateEffects.keys,
    };
    var changed = true;
    while (changed) {
      changed = false;
      for (final node in all) {
        if (advancing.contains(node.id)) continue;
        final dependents = _dependentTechnologyIds[node.id] ?? const {};
        if (dependents.any(advancing.contains)) {
          advancing.add(node.id);
          changed = true;
        }
      }
    }
    return Set.unmodifiable(advancing);
  }

